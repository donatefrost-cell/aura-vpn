export function normalizeDnsMode(
  mode?: string | null,
): Exclude<DnsMode, 'auto'> {
  const low = (mode ?? '').trim().toLowerCase();
  if (low === 'vpn') return 'vpn';
  if (low === 'config') return 'config';
  if (low === 'system') return 'system';
  if (low === 'custom') return 'custom';
  return 'hybrid';
}
